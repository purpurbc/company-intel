CREATE TABLE meta.source (
    code text PRIMARY KEY,
    name text NOT NULL
);
INSERT INTO meta.source VALUES
    ('scb_api', 'SCB API'), ('scb_bulk', 'SCB bulk'),
    ('bolagsverket', 'Bolagsverket bulk'), ('legacy', 'Migrated v1 data');

CREATE TABLE meta.ingestion_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL REFERENCES meta.source(code),
    dataset text NOT NULL DEFAULT 'company',
    started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at timestamptz,
    source_as_of_date date,
    filename text,
    file_checksum text,
    schema_version text NOT NULL DEFAULT '2',
    metadata jsonb NOT NULL DEFAULT '{}',
    records_seen bigint NOT NULL DEFAULT 0 CHECK (records_seen >= 0),
    records_new bigint NOT NULL DEFAULT 0 CHECK (records_new >= 0),
    records_changed bigint NOT NULL DEFAULT 0 CHECK (records_changed >= 0),
    records_skipped bigint NOT NULL DEFAULT 0 CHECK (records_skipped >= 0),
    last_row_number bigint NOT NULL DEFAULT 0,
    status text NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'done', 'failed', 'interrupted')),
    error text
);
CREATE INDEX ingestion_run_file ON meta.ingestion_run(source, file_checksum, id DESC);

CREATE TABLE meta.data_quality_issue (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ingestion_run_id bigint NOT NULL REFERENCES meta.ingestion_run(id),
    row_number bigint,
    issue_code text NOT NULL,
    detail text NOT NULL,
    observed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Code domains keep different authorities' codes apart. Codes are identifiers, not numbers.
CREATE TABLE meta.code (
    source text NOT NULL REFERENCES meta.source(code),
    domain text NOT NULL,
    code text NOT NULL,
    name text NOT NULL,
    parent_code text,
    PRIMARY KEY (source, domain, code)
);

