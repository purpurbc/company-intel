-- JSON (not JSONB) preserves escaped NULs from malformed source text.
-- Keep the original files too: payload is an exact decoded record, not the original bytes.
CREATE TABLE raw.company_record (
    source text NOT NULL REFERENCES meta.source(code),
    ingestion_run_id bigint NOT NULL REFERENCES meta.ingestion_run(id),
    row_number bigint NOT NULL,
    source_file text,
    payload json NOT NULL,
    raw_hash text NOT NULL,
    observed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (source, ingestion_run_id, row_number)
) PARTITION BY LIST (source);
CREATE TABLE raw.scb_api_company PARTITION OF raw.company_record FOR VALUES IN ('scb_api');
CREATE TABLE raw.scb_bulk_company PARTITION OF raw.company_record FOR VALUES IN ('scb_bulk');
CREATE TABLE raw.bolagsverket_company PARTITION OF raw.company_record FOR VALUES IN ('bolagsverket');
CREATE TABLE raw.legacy_company PARTITION OF raw.company_record FOR VALUES IN ('legacy');

CREATE FUNCTION raw.reject_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Raw records are immutable; import a new observation instead';
END;
$$;
CREATE TRIGGER immutable_company_record BEFORE UPDATE OR DELETE ON raw.company_record
    FOR EACH ROW EXECUTE FUNCTION raw.reject_mutation();

REVOKE ALL ON SCHEMA raw, src_scb, src_bolagsverket, core, meta FROM PUBLIC;
